    private static readonly Dictionary<string, Dictionary<string, string>> ToLocal = new(StringComparer.OrdinalIgnoreCase)
    {
        ["it"] = ItNames,
        ["de"] = DeNames,
        ["es"] = EsNames,
        ["fr"] = FrNames,
    };

    private static readonly Dictionary<string, Dictionary<string, string>> ToEnglish =
    ToLocal.ToDictionary(
        pair => pair.Key,
        pair => pair.Value.GroupBy(entry => entry.Value, StringComparer.OrdinalIgnoreCase)
                          .ToDictionary(group => group.Key, group => group.First().Key,
                                        StringComparer.OrdinalIgnoreCase),
        StringComparer.OrdinalIgnoreCase);

    public IReadOnlyList<string> SupportedLanguages { get; } = ["en", "it", "de", "es", "fr"];

    public string ToCanonical(string name, string language)
    {
        ArgumentNullException.ThrowIfNull(name);

        if (!ToEnglish.TryGetValue(Normalize(language), out var table)) return name;
        return table.GetValueOrDefault(name, name);
    }

    public string ToLanguage(string canonicalName, string language)
    {
        ArgumentNullException.ThrowIfNull(canonicalName);

        if (!ToLocal.TryGetValue(Normalize(language), out var table)) return canonicalName;
        return table.GetValueOrDefault(canonicalName, canonicalName);
    }

    public IEnumerable<string> NamesIn(string language) =>
        ToLocal.TryGetValue(Normalize(language), out var table) ? table.Values : [];

    private static string Normalize(string language) =>
        string.IsNullOrWhiteSpace(language) ? "en" : language.Split('-')[0].ToLowerInvariant();
